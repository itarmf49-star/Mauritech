/**
 * يولّد slug آمناً لعناوين الروابط — يبقيه ASCII بحت (a-z0-9 وشرطات) عمداً، حتى مع
 * عنوان عربي بالكامل. الإبقاء على حروف عربية داخل الـ slug (كما كان يحدث سابقاً) كان
 * يُسبب أعطالاً حقيقية: انتقال المتصفح لرابط كهذا يمر بتشفير/فك‌تشفير URL قد يُنتج شكلاً
 * مختلفاً Unicode-normalization عمّا يصل للخادم، فتفشل مطابقته مع القيمة المخزّنة في
 * القاعدة رغم تطابق الشكل الظاهري تماماً — صفحة "غير موجودة" رغم وجود المحتوى فعلياً.
 * الحل القياسي: slugs بأحرف ASCII فقط دائماً، بغض النظر عن لغة العنوان.
 */
export function slugify(input: string): string {
  const ascii = input
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "") // إزالة علامات التشكيل عن الحروف اللاتينية (é → e)
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "") // يُسقط أي شيء آخر (عربي، رموز...) بدل تركه في الرابط
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");

  if (ascii) return ascii;

  // عنوان بلا أي حرف لاتيني (عربي بالكامل مثلاً) — نولّد معرّفاً عشوائياً قصيراً بدل
  // ترك الحقل فارغاً أو محاولة نقل الأحرف العربية كما هي إلى الرابط.
  return `item-${Math.random().toString(36).slice(2, 8)}`;
}
